class Database {
  private data: DatabaseSchema;

  constructor() {
    this.ensureDataDir();
    this.data = this.loadData();
  }

  private ensureDataDir() {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
  }

  private loadData(): DatabaseSchema {
    try {
      if (fs.existsSync(DB_FILE)) {
        const raw = fs.readFileSync(DB_FILE, 'utf-8');
        const parsed = JSON.parse(raw);
        if (parsed.settings) {
          parsed.settings.enableEitherTeamWinModel = parsed.settings.enableEitherTeamWinModel ?? true;
          parsed.settings.eitherTeamWinThresholdPercent = parsed.settings.eitherTeamWinThresholdPercent ?? 70;
        }
        return parsed;
      }
    } catch (e) {
      console.error('Error reading database file, initializing fresh:', e);
    }
    const initial = createInitialDatabase();
    this.saveData(initial);
    return initial;
  }

  private saveData(dataToSave: DatabaseSchema) {
    try {
      this.ensureDataDir();
      fs.writeFileSync(DB_FILE, JSON.stringify(dataToSave, null, 2), 'utf-8');
    } catch (e) {
      console.error('Error persisting database file:', e);
    }
  }

  public getSettings(): AppSettings {
    return this.data.settings;
  }

  public updateSettings(partial: Partial<AppSettings>): AppSettings {
    this.data.settings = { ...this.data.settings, ...partial };
    this.saveData(this.data);
    return this.data.settings;
  }

  public getFixtures(date?: string, competitionId?: string): Fixture[] {
    let result = this.data.fixtures;
    if (date) {
      result = result.filter((f) => f.date === date);
    }
    if (competitionId && competitionId !== 'all') {
      result = result.filter((f) => f.competitionId === competitionId);
    }
    return result;
  }

  public getFixtureById(id: string): Fixture | undefined {
    return this.data.fixtures.find((f) => f.id === id);
  }

  public upsertFixtures(fixtures: Fixture[]) {
    const existingMap = new Map<string, Fixture>();
    this.data.fixtures.forEach((f) => existingMap.set(f.id, f));
    fixtures.forEach((f) => existingMap.set(f.id, f));
    this.data.fixtures = Array.from(existingMap.values());
    this.saveData(this.data);
  }

  public getTeamHistory(teamName: string): HistoricalMatch[] {
    return this.data.teamHistories[teamName] || [];
  }

  public saveTeamHistory(teamName: string, matches: HistoricalMatch[]) {
    this.data.teamHistories[teamName] = matches;
    this.saveData(this.data);
  }

  public getAllTeamHistories(): Record<string, HistoricalMatch[]> {
    return this.data.teamHistories;
  }

  public getLockedPrediction(fixtureId: string): PredictionDetail | undefined {
    return this.data.lockedPredictions[fixtureId];
  }

  public saveLockedPrediction(prediction: PredictionDetail) {
    this.data.lockedPredictions[prediction.fixtureId] = prediction;
    this.saveData(this.data);
  }

  public getEvaluatedResults() {
    return this.data.evaluatedResults;
  }

  public addEvaluatedResult(result: DatabaseSchema['evaluatedResults'][0]) {
    this.data.evaluatedResults.unshift(result);
    this.saveData(this.data);
  }

  public getPerformanceStats(): PerformanceStats {
    return evaluateModelPerformance(this.data.evaluatedResults);
  }
}

export const dbInstance = new Database();
